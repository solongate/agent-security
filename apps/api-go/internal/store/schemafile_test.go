package store_test

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/codeyevsky/solongate/api/internal/store"
)

// The checked-in schema files are what this package generates, byte for byte.
//
// They are checked in because a DBA applies them and a review reads them, and
// generated because writing them by hand is how they stop matching the product.
// Both of those are only true while the file on disk is the file the generator
// produces — a schema that has drifted is worse than no schema, because it looks
// authoritative.
//
// It fails with the command to fix it rather than with a diff, because the fix is
// always the same and never "edit the file".
func TestCheckedInSchemaFilesMatchTheGenerator(t *testing.T) {
	for _, tc := range []struct {
		file    string
		dialect store.Dialect
		name    string
	}{
		{"sqlite.sql", store.SQLite, "sqlite"},
		{"postgres.sql", store.Postgres, "postgres"},
	} {
		path := filepath.Join("..", "..", "..", "..", "tools", "schema", tc.file)
		onDisk, err := os.ReadFile(path)
		if err != nil {
			t.Errorf("tools/schema/%s: %v", tc.file, err)
			continue
		}

		base, err := store.BaseDDL(tc.dialect)
		if err != nil {
			t.Fatalf("BaseDDL(%s): %v", tc.name, err)
		}
		stmts := append(base, store.RuntimeDDL(tc.dialect)...)

		var b strings.Builder
		b.WriteString("-- SolonGate schema for " + tc.name + ": ")
		b.WriteString(itoa(len(stmts)))
		b.WriteString(" statements.\n")
		b.WriteString("-- Generated by apps/api-go/cmd/schemadump. Do not edit by hand.\n\n")
		for _, s := range stmts {
			b.WriteString(strings.TrimSpace(s))
			b.WriteString(";\n\n")
		}

		if string(onDisk) != b.String() {
			t.Errorf("tools/schema/%s has drifted from the generator. Regenerate it:\n"+
				"  cd apps/api-go && go run ./cmd/schemadump -dialect %s > ../../tools/schema/%s",
				tc.file, tc.name, tc.file)
		}
	}
}

// itoa keeps this test off strconv, so the expected header is assembled the same
// way in one place and cannot disagree with itself.
func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	var digits []byte
	for n > 0 {
		digits = append([]byte{byte('0' + n%10)}, digits...)
		n /= 10
	}
	return string(digits)
}
