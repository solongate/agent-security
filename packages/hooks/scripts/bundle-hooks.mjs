// Bundles the cloud guard hook into a single self-contained .mjs so it can run
// from ~/.solongate/hooks/ WITHOUT a node_modules directory next to it.
//
// guard.mjs imports its decision engine from the sibling policy-eval.mjs. A
// GLOBAL install (init --global) drops the hook as a lone file referenced from
// ~/.claude/settings.json, with no sibling beside it, so that import has to be
// inlined here at build time or it would MODULE_NOT_FOUND on the host and
// enforcement would silently fail-closed (DENY everything).
//
// Output (guard.bundled.mjs) is committed; the installer prefers it over the
// readable guard.mjs when present.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const hooks = resolve(here, '..');

await build({
  entryPoints: [resolve(hooks, 'guard.mjs')],
  bundle: true,
  platform: 'node',     // keeps node:* built-ins external
  format: 'esm',
  target: 'node18',
  outfile: resolve(hooks, 'guard.bundled.mjs'),
  banner: {
    // The SPDX line comes from here rather than from the source file, because
    // this output is rewritten on every build and a line added to it by hand
    // would last only until the next one.
    js: '// SPDX-License-Identifier: Apache-2.0\n'
      + '// AUTO-GENERATED by scripts/bundle-hooks.mjs. DO NOT EDIT.\n'
      + '// Edit the source hook and run `pnpm --filter @solongate/hooks build`.',
  },
  legalComments: 'none',
});

console.log('[bundle-hooks] guard.mjs -> guard.bundled.mjs');
