import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const hooks = resolve(here, '..');

await build({
  entryPoints: [resolve(hooks, 'guard.mjs')],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node18',
  outfile: resolve(hooks, 'guard.bundled.mjs'),
  banner: {
    // REUSE-IgnoreStart
    js: '// SPDX-License-Identifier: Apache-2.0\n'
      + '// Copyright 2026 the SolonGate contributors\n'
      + '// AUTO-GENERATED by scripts/bundle-hooks.mjs. DO NOT EDIT.\n'
      + '// Edit the source hook and run `pnpm --filter @solongate/hooks build`.',
    // REUSE-IgnoreEnd
  },
  legalComments: 'none',
});

console.log('[bundle-hooks] guard.mjs -> guard.bundled.mjs');