/**
 * Regenerates internal/install/launcher_script.go from the npm package's
 * hook-launcher.ts, which is the single source of truth for the launcher.
 *
 * Both implementations write ~/.solongate/hooks/sg-run.sh, and whichever ran
 * last wins. If they disagreed by even one byte, a machine with both installed
 * would have each rewriting the other's copy on every run — and the two node
 * search orders would drift apart without anyone noticing, which is the class of
 * bug the launcher exists to end. npmparity_test.go compares the two files, so
 * the drift fails the build; this script is how you fix it.
 *
 *   node scripts/gen-launcher.mjs
 *
 * Run it after editing packages/proxy/src/hook-launcher.ts.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dist = resolve(here, '..', '..', 'proxy', 'dist', 'global-install.js');
if (!existsSync(dist)) {
  console.error(`no ${dist} — run \`pnpm build\` in packages/proxy first`);
  process.exit(1);
}

const PIN = '__SOLONGATE_PINNED_NODE__';
const { launcherScript } = await import(`file://${dist}`);
const script = launcherScript(PIN);

if (!script.includes(PIN)) {
  console.error('the generated script does not contain the pin placeholder');
  process.exit(1);
}

/**
 * The script as a Go expression.
 *
 * Raw string literals cannot contain a backtick and the script has several, so
 * the text is split on them and the backticks are re-added as interpreted
 * literals. The pin becomes a concatenated variable at each site it appears.
 */
function goExpr(text) {
  const parts = [];
  for (const chunk of text.split('`')) {
    if (parts.length) parts.push('"`"');
    for (const [i, piece] of chunk.split(PIN).entries()) {
      if (i) parts.push('pinned');
      if (piece) parts.push('`' + piece + '`');
    }
  }
  return parts.join(' +\n\t\t');
}

const out = `// Code generated by scripts/gen-launcher.mjs. DO NOT EDIT.
//
// The source is packages/proxy/src/hook-launcher.ts. Both implementations write
// the same ~/.solongate/hooks/sg-run.sh and whichever ran last wins, so a byte
// of difference would have each rewriting the other's copy on every install —
// and the two node search orders drifting apart unnoticed. npmparity_test.go
// compares the files; regenerate this one rather than editing it.

package install

import (
	"path/filepath"
	"strings"
)

// launcherScript is the launcher with the install-time node baked in. See
// launcher.go for what it is for and why it is not a node path in the config.
func launcherScript(pinnedNode string) string {
	pinned := strings.ReplaceAll(filepath.ToSlash(pinnedNode), \`'\`, \`'\\''\`)
	return ${goExpr(script)}
}
`;

const target = join(here, '..', 'internal', 'install', 'launcher_script.go');
writeFileSync(target, out);
try {
  execFileSync('gofmt', ['-w', target]);
} catch {
  /* gofmt is a nicety here; the generator emits formatted code */
}
console.log(`wrote ${target} (${script.length} bytes of script)`);
